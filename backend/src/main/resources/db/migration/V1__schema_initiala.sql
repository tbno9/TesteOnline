CREATE TABLE utilizator (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume      VARCHAR(100) NOT NULL,
    email     VARCHAR(150) NOT NULL UNIQUE,
    parola    VARCHAR(255) NOT NULL,
    rol       VARCHAR(20)  NOT NULL CHECK (rol IN ('PROFESOR', 'STUDENT'))
);

CREATE TABLE test (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titlu          VARCHAR(150)  NOT NULL,
    descriere      VARCHAR(1000),
    domeniu        VARCHAR(100)  NOT NULL,
    durata_minute  INTEGER       NOT NULL CHECK (durata_minute > 0),
    autor_id       BIGINT        NOT NULL REFERENCES utilizator (id)
);

CREATE TABLE intrebare (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text     VARCHAR(1000) NOT NULL,
    punctaj  INTEGER NOT NULL DEFAULT 1 CHECK (punctaj > 0),
    ordine   INTEGER NOT NULL,
    test_id  BIGINT  NOT NULL REFERENCES test (id) ON DELETE CASCADE
);

CREATE TABLE varianta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text          VARCHAR(500) NOT NULL,
    corecta       BOOLEAN NOT NULL DEFAULT FALSE,
    intrebare_id  BIGINT  NOT NULL REFERENCES intrebare (id) ON DELETE CASCADE
);

CREATE TABLE incercare (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_id       BIGINT    NOT NULL REFERENCES test (id),
    student_id    BIGINT    NOT NULL REFERENCES utilizator (id),
    inceputa_la   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    terminata_la  TIMESTAMP,
    scor          NUMERIC(6, 2)
);

CREATE TABLE raspuns_ales (
    incercare_id  BIGINT NOT NULL REFERENCES incercare (id) ON DELETE CASCADE,
    varianta_id   BIGINT NOT NULL REFERENCES varianta (id),
    PRIMARY KEY (incercare_id, varianta_id)
);


